// Bakes the "moments" wordmark (Google Sans Flex Display 600) into SVG path data, one path per glyph so the
// letters can animate independently. Output: src/components/brand/wordmark-paths.ts
// Usage: node scripts/gen-wordmark.mjs
import fs from 'node:fs';
import path from 'node:path';
import opentype from 'opentype.js';

const FONT = path.resolve('assets/fonts/GoogleSansFlex-Display600.ttf');
const OUT = path.resolve('src/components/brand/wordmark-paths.ts');

const buf = fs.readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const TEXT = 'moments';
const SIZE = 100;
const TRACK = -3; // display tracking (−0.03em), like the headlines

// Pass 1: layout + ink bounds.
const layout = [];
let x = 0;
for (const ch of TEXT) {
  const g = font.charToGlyph(ch);
  layout.push({ ch, g, x });
  x += (g.advanceWidth / font.unitsPerEm) * SIZE + TRACK;
}
let minX = Infinity;
let maxX = -Infinity;
let minY = Infinity;
let maxY = -Infinity;
for (const l of layout) {
  const bb = l.g.getPath(l.x, 0, SIZE).getBoundingBox();
  minX = Math.min(minX, bb.x1);
  maxX = Math.max(maxX, bb.x2);
  minY = Math.min(minY, bb.y1);
  maxY = Math.max(maxY, bb.y2);
}

// opentype.js 2.x's toPathData emits NaN for some quadratic control points, so serialise ourselves.
const n = (v) => {
  if (!Number.isFinite(v)) throw new Error('non-finite coordinate in glyph path');
  return Math.round(v * 100) / 100;
};
function serialize(cmds) {
  return cmds
    .map((c) => {
      if (c.type === 'M' || c.type === 'L') return `${c.type}${n(c.x)} ${n(c.y)}`;
      if (c.type === 'Q') return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
      if (c.type === 'C') return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
      return 'Z';
    })
    .join('');
}

// Pass 2: emit glyph paths shifted so the ink box starts at (0, 0).
const glyphs = layout.map((l) => {
  const p = l.g.getPath(l.x - minX, -minY, SIZE);
  const bb = p.getBoundingBox();
  return { ch: l.ch, d: serialize(p.commands), cx: (bb.x1 + bb.x2) / 2 };
});

const width = Math.ceil(maxX - minX);
const height = Math.ceil(maxY - minY);
const body = glyphs.map((g) => `  { ch: '${g.ch}', d: '${g.d}', cx: ${g.cx.toFixed(1)} },`).join('\n');

fs.writeFileSync(
  OUT,
  `// Generated by scripts/gen-wordmark.mjs from Google Sans Flex Display 600 — do not edit by hand.\nexport const WORDMARK_WIDTH = ${width};\nexport const WORDMARK_HEIGHT = ${height};\nexport const WORDMARK_GLYPHS: { ch: string; d: string; cx: number }[] = [\n${body}\n];\n`,
);
console.log('wrote', OUT, { width, height });
